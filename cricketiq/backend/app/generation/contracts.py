"""Protocol and data contracts for LLM generation in CricketIQ."""

from __future__ import annotations
from typing import List, Optional, Dict, Any, Protocol
from pydantic import BaseModel, Field


class ClaimMapping(BaseModel):
    """Substantive statement paired with supporting cited clause IDs."""
    claim_text: str = Field(..., description="A specific factual rule claim made in the answer")
    supporting_clause_ids: List[str] = Field(
        default_factory=list,
        description="Clause IDs cited as evidence for this claim"
    )


class StructuredDraftAnswer(BaseModel):
    """Raw structured output generated by an LLM before deterministic validation."""
    summary: str = Field(..., description="High level summary of the answer")
    detailed_explanation: str = Field(..., description="Full regulatory explanation")
    key_points: List[str] = Field(default_factory=list, description="Core summary bullets")
    exceptions_and_edge_cases: List[str] = Field(default_factory=list, description="Exceptions and conditions")
    historical_context: Optional[str] = Field(default=None, description="Edition comparison or notes on rule changes")
    citations_used: List[str] = Field(
        default_factory=list,
        description="List of clause IDs cited from the evidence pack"
    )
    claim_mappings: List[ClaimMapping] = Field(
        default_factory=list,
        description="Mapping connecting claims to cited clause IDs"
    )
    raw_response: str = Field(default="", description="Verbatim raw response string from model")


